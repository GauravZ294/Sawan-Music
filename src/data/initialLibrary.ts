const enrichWithMoodTags = (song: Song): Song => {
  if (song.moodLabels && song.moodLabels.length > 0) return song;

  const category = song.category || 'regular';
  const bpm = song.bpm || 80;
  const genre = (song.genre || '').toLowerCase();
  const title = (song.title || '').toLowerCase();
  const mood = (song.mood || '').toLowerCase();

  let primaryMood: 'Workout' | 'Relaxing' | 'Party' | 'Romantic' | 'Focus' | 'Road Trip' = 'Relaxing';
  let energyLevel: 'Low' | 'Medium' | 'High' | 'Extreme' = 'Medium';
  const moodLabels: string[] = [];
  let vibes = '';

  const isParty =
    category === 'remix' ||
    /party|club|dance|remix|dj|dhol|bhangra|chull|kala chashma|dilbar|nachde|aankh marey|gallan/i.test(
      genre + ' ' + title + ' ' + mood
    );
  const isWorkout =
    bpm >= 115 ||
    category === 'remix' ||
    /workout|gym|cardio|fitness|energy|fast/i.test(genre + ' ' + title + ' ' + mood);
  const isRelaxing =
    category === 'lofi' ||
    category === 'acoustic' ||
    bpm <= 82 ||
    /lofi|chill|slow|reverb|calm|peaceful/i.test(genre + ' ' + title + ' ' + mood);
  const isRomantic = /romantic|love|dil|ishq|pyar|chahun|tum hi ho|kesariya|raataan|mohabbat/i.test(
    genre + ' ' + title + ' ' + mood
  );

  if (isParty) {
    primaryMood = 'Party';
    moodLabels.push('Party', 'Workout', 'High Energy');
    if (category === 'remix') moodLabels.push('Club Remix');
    energyLevel = bpm >= 125 ? 'Extreme' : 'High';
    vibes = `Heavy groove and explosive ${bpm} BPM rhythm make this an explosive party banger and workout booster.`;
  } else if (isWorkout) {
    primaryMood = 'Workout';
    moodLabels.push('Workout', 'Party', 'Cardio Fuel');
    energyLevel = 'High';
    vibes = `High tempo driving pulse (${bpm} BPM) engineered for fitness reps, cardio, and running.`;
  } else if (isRelaxing) {
    primaryMood = 'Relaxing';
    moodLabels.push('Relaxing', 'Lo-Fi Chill', 'Evening Calm');
    energyLevel = bpm <= 75 ? 'Low' : 'Medium';
    vibes = `Laid-back acoustic tones and relaxed cadences, ideal for unwinding, studying, and late-night calm.`;
  } else if (isRomantic) {
    primaryMood = 'Romantic';
    moodLabels.push('Romantic', 'Relaxing', 'Soulful');
    energyLevel = 'Medium';
    vibes = `Heartfelt poetic sentiments and emotional melodic curves designed for romantic listening.`;
  } else {
    primaryMood = 'Focus';
    moodLabels.push('Focus', 'Relaxing');
    energyLevel = 'Medium';
    vibes = `Smooth rhythmic continuity suited for background concentration.`;
  }

  return {
    ...song,
    language: song.language || 'Hindi',
    moodLabels,
    energyLevel,
    aiMoodAnalysis: {
      primaryMood,
      vibes,
      confidence: 0.95,
      suggestedPlaylists: [primaryMood + ' Bollywood', 'Auto Curated'],
    },
  };
};

